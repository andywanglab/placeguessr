// Add random jitter (~2-8km) so same city = different street each game
function jitter(lat, lng) {
  const offset = 0.02 + Math.random() * 0.06; // 2-8km range
  const angle = Math.random() * Math.PI * 2;
  return [
    Math.round((lat + offset * Math.sin(angle)) * 10000) / 10000,
    Math.round((lng + offset * Math.cos(angle)) * 10000) / 10000,
  ];
}

export function getRandomLocations(count = 5) {
  const shuffled = [...locations].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count).map(([lat, lng, name]) => {
    const [jLat, jLng] = jitter(lat, lng);
    return { lat: jLat, lng: jLng, name };
  });
}

export function getOneRandomLocation() {
  const [lat, lng, name] = locations[Math.floor(Math.random() * locations.length)];
  const [jLat, jLng] = jitter(lat, lng);
  return { lat: jLat, lng: jLng, name };
}

